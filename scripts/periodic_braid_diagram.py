# The dataset generated by configs/experiments/default.yaml, used as the
# input when none is given so reproducing the default figure needs no flags.
_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_INPUT = _ROOT / "data/state-tracking-long-context-v1/canonical/test.jsonl"

# The periodic record rendered when no --instance-id/--index/--shortest is
# given, so re-running the script with no selection arguments always
# reproduces the same figure. A short (32-assignment) trace with a scratch
# (TMP) register, from the dataset at DEFAULT_INPUT.
DEFAULT_INSTANCE_ID = "0172d972c607da91c421"


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "input",
        type=Path,
        nargs="?",
        default=DEFAULT_INPUT,
        help=f"Canonical JSONL dataset input. Defaults to {DEFAULT_INPUT.relative_to(_ROOT)}.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        required=True,
        help="Destination image path; use a .pdf or .svg suffix for vector output.",
    )
    selection = parser.add_mutually_exclusive_group()
    selection.add_argument(
        "--instance-id",
        help="Render the periodic record with this instance ID.",
    )
    selection.add_argument(
        "--index",
        type=int,
        help="Render this zero-based periodic-record index.",
    )
    selection.add_argument(
        "--shortest",
        action="store_true",
        help="Render the shortest periodic record (preferring fewer variables on ties).",
    )
    parser.add_argument("--title", help="Optional plot title.")
    parser.add_argument(
        "--num-distractors",
        type=int,
        default=4,
        help="Incorrect answer choices to draw beside the braid; 0 omits the panel.",
    )
    parser.add_argument(
        "--distractor-seed",
        type=int,
        default=0,
        help="Random seed for generating and shuffling the answer choices.",
    )
    args = parser.parse_args(argv)
    if args.instance_id is None and args.index is None and not args.shortest:
        args.instance_id = DEFAULT_INSTANCE_ID
    return args


def select_record(
    path: Path,
    *,
    instance_id: str | None,
    index: int | None,
    shortest: bool,
) -> dict[str, Any]:
    """Select one periodic record without retaining the full dataset in memory."""

    selected: dict[str, Any] | None = None
    selected_key: tuple[int, int] | None = None
    periodic_index = 0
    with path.open() as handle:
        for line in handle:
            record = json.loads(line)
            if record["complexity"] != "periodic":
                continue
            if instance_id is not None and record["instance_id"] == instance_id:
                return record
            if index is not None and periodic_index == index:
                return record
            if shortest or (instance_id is None and index is None):
                key = (int(record["num_extra_assignments"]), int(record["num_variables"]))
                if selected_key is None or key < selected_key:
                    selected = record
                    selected_key = key
            periodic_index += 1

    if instance_id is not None:
        raise ValueError(f"no periodic record has instance ID {instance_id!r}")
    if index is not None:
        raise IndexError(f"periodic-record index {index} is out of range")
    if selected is None:
        raise ValueError(f"no periodic records found in {path}")
    return selected


def variable_labels(num_variables: int, temporary_variable: int | None) -> list[str]:
    """Use integer-code-style names for real variables and the scratch register."""

    labels = [chr(ord("a") + index) if index < 26 else f"v{index}" for index in range(num_variables)]
    if temporary_variable is not None:
        if temporary_variable != num_variables:
            raise ValueError("temporary variable must follow the real variables")
        labels.append("TMP")
    return labels


def initial_state(record: dict[str, Any]) -> tuple[list[int], list[dict[str, Any]]]:
    """Evaluate initialization and return the state plus remaining operations."""

    num_registers = int(record["num_variables"]) + (record.get("temporary_variable") is not None)
    operations = record["operations"]
    state: list[int | None] = [None] * num_registers
    for operation in operations[:num_registers]:
        if operation["op"] != "constant":
            raise ValueError("expected every initialization operation to assign a constant")
        state[int(operation["target"])] = int(operation["value"])
    if any(value is None for value in state):
        raise ValueError("initialization does not assign every register")
    return [int(value) for value in state], operations[num_registers:]


_BACKGROUND = "#ffffff"
_TRACK_COLOR = "#e9e9ee"
_INK = "#2a2a30"
_STRAND_WIDTH = 3.4
_CASING_EXTRA = 3.0


# Tuned by eye: L_MIN/L_MAX bound how light or dark a hue is allowed to get
# while searching for its most vivid rendering (kept short of pastel and short
# of neon-bright). TARGET_CHROMA is an absolute chroma, not a fraction of each
# hue's own gamut-edge maximum: sRGB simply cannot make yellow-green or teal
# as saturated as it can red or blue at these lightnesses, so scaling off each
# hue's own ceiling left the weak hues looking muddy next to the vivid ones.
# Capping every hue to the same absolute value instead equalizes how rich
# they look, at the cost of the naturally-vivid hues giving up some headroom.
# Covers the worst case of 16 real variables plus a scratch register.
_PALETTE_L_MIN = 0.45
_PALETTE_L_MAX = 0.68
_PALETTE_TARGET_CHROMA = 0.15
_PALETTE_HUE_OFFSET = 0.0
_PALETTE_MAX_VALUES = 17


def _oklab_to_linear_srgb(lightness: float, a: float, b: float) -> tuple[float, float, float]:
    """OKLab -> linear-sRGB, via Björn Ottosson's published OKLab matrices."""

    l_ = lightness + 0.3963377774 * a + 0.2158037573 * b
    m_ = lightness - 0.1055613458 * a - 0.0638541728 * b
    s_ = lightness - 0.0894841775 * a - 1.2914855480 * b
    l, m, s = l_**3, m_**3, s_**3
    red = 4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s
    green = -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s
    blue = -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s
    return red, green, blue


def _linear_to_srgb(value: float) -> float:
    value = max(value, 0.0)
    if value <= 0.0031308:
        return 12.92 * value
    return 1.055 * value ** (1 / 2.4) - 0.055


def _oklch_to_srgb(lightness: float, chroma: float, hue_degrees: float) -> tuple[float, float, float]:
    hue = math.radians(hue_degrees)
    red, green, blue = _oklab_to_linear_srgb(lightness, chroma * math.cos(hue), chroma * math.sin(hue))
    return tuple(_linear_to_srgb(channel) for channel in (red, green, blue))


def _oklch_in_gamut(lightness: float, chroma: float, hue_degrees: float) -> bool:
    hue = math.radians(hue_degrees)
    red, green, blue = _oklab_to_linear_srgb(lightness, chroma * math.cos(hue), chroma * math.sin(hue))
    return all(-1e-6 <= channel <= 1 + 1e-6 for channel in (red, green, blue))


def _max_oklch_chroma(lightness: float, hue_degrees: float, *, iterations: int = 24) -> float:
    """Binary-search the most saturated in-gamut sRGB color at this lightness/hue."""

    low, high = 0.0, 0.4
    for _ in range(iterations):
        mid = (low + high) / 2
        if _oklch_in_gamut(lightness, mid, hue_degrees):
            low = mid
        else:
            high = mid
    return low


def _most_vivid_lightness(hue_degrees: float, *, steps: int = 16) -> tuple[float, float]:
    """The lightness in [L_MIN, L_MAX] with the largest in-gamut chroma at this hue.

    Yellow can only be truly vivid near white, and blue near black, so no
    single fixed lightness looks equally rich across every hue; this lets
    each hue claim its own best lightness within the allowed band instead of
    forcing yellows into a muddy olive to match the others.
    """

    best_lightness, best_chroma = _PALETTE_L_MIN, -1.0
    for step in range(steps):
        lightness = _PALETTE_L_MIN + (_PALETTE_L_MAX - _PALETTE_L_MIN) * step / (steps - 1)
        chroma = _max_oklch_chroma(lightness, hue_degrees)
        if chroma > best_chroma:
            best_lightness, best_chroma = lightness, chroma
    return best_lightness, best_chroma


def _value_palette(values: Sequence[int]) -> dict[int, tuple[float, float, float]]:
    """A refined, evenly-hued qualitative palette keyed by observed value.

    Hues are spaced evenly by angle rather than by perceptual distance: an
    equal-Lab-distance spacing sounds more rigorous, but blue and purple can
    reach much higher chroma than yellow or orange within sRGB, so it in
    practice claims a disproportionate share of hues for the blue family and
    crowds out warm colors. Plain angular spacing keeps every hue family
    represented, which reads as more diverse even though adjacent hues are
    not perfectly equalized for distance.
    """

    count = len(values)
    if count > _PALETTE_MAX_VALUES:
        raise ValueError(f"palette supports at most {_PALETTE_MAX_VALUES} distinct values, got {count}")
    colors = []
    for index in range(count):
        hue = (_PALETTE_HUE_OFFSET + 360.0 * index / count) % 360 if count else 0.0
        lightness, chroma_max = _most_vivid_lightness(hue)
        colors.append(_oklch_to_srgb(lightness, min(_PALETTE_TARGET_CHROMA, chroma_max), hue))
    return dict(zip(values, colors, strict=False))


def _time_ticks(max_step: int, target: int = 10) -> list[int]:
    """Round-stride tick positions from 0, always including the final step.

    The stride is the smallest 1/2/5 x 10^k value that keeps the count near
    ``target``, so labels land on round numbers instead of a floored even split.
    """

    if max_step <= target:
        step = 1
    else:
        raw = max_step / target
        magnitude = 10.0 ** math.floor(math.log10(raw))
        step = next(
            (int(factor * magnitude) for factor in (1, 2, 5, 10) if factor * magnitude >= raw),
            int(10 * magnitude),
        )
    ticks = list(range(0, max_step + 1, max(step, 1)))
    if ticks[-1] != max_step:
        ticks.append(max_step)
    # Drop a penultimate tick that would crowd the always-present final one.
    if len(ticks) >= 2 and ticks[-1] - ticks[-2] < step * 0.6:
        del ticks[-2]
    return ticks


def _smooth_crossing(x0: float, x1: float, y0: float, y1: float, samples: int = 72) -> tuple[Any, Any]:
    """Sample a smootherstep S-curve with horizontal tangents at both ends."""

    fraction = np.linspace(0.0, 1.0, samples)
    eased = fraction * fraction * fraction * (fraction * (fraction * 6.0 - 15.0) + 10.0)
    return x0 + (x1 - x0) * fraction, y0 + (y1 - y0) * eased


def _draw_strand(axis: Any, xs: Any, ys: Any, color: Any, *, zorder: float) -> None:
    """Draw one colored strand cased in the background color for a woven look."""

    axis.plot(
        xs,
        ys,
        color=color,
        linewidth=_STRAND_WIDTH,
        solid_capstyle="round",
        solid_joinstyle="round",
        zorder=zorder,
        path_effects=[
            pe.Stroke(linewidth=_STRAND_WIDTH + _CASING_EXTRA, foreground=_BACKGROUND),
            pe.Normal(),
        ],
    )


_GREEK_LOWER = "αβγδεζηθικλμνξοπρστυφχψω"


def _greek_label(index: int) -> str:
    """Label a zero-based choice index with a lowercase Greek letter."""

    if index < len(_GREEK_LOWER):
        return _GREEK_LOWER[index]
    return f"{_GREEK_LOWER[index % len(_GREEK_LOWER)]}{index // len(_GREEK_LOWER) + 1}"


def _answer_choices(
    record: dict[str, Any], *, num_distractors: int, seed: int
) -> list[tuple[bool, tuple[int, ...]]]:
    """Return shuffled (is_correct, state) choices, one of them the true final state."""

    instance = StateTrackingInstance.from_record(record)
    rng = random.Random(seed)
    wrong_states = generate_incorrect_states(instance, num_distractors=num_distractors, rng=rng)
    entries = [(True, instance.final_state), *((False, state) for state in wrong_states)]
    rng.shuffle(entries)
    return entries


_CORRECT_MARK_COLOR = "#2ca02c"


def _draw_choices_panel(
    axis: Any,
    *,
    anchor_x: float,
    choices: Sequence[tuple[bool, tuple[int, ...]]],
    query: Sequence[int],
    labels: Sequence[str],
    colors: dict[int, Any],
) -> None:
    """Add a color-coded multiple-choice panel to the right of the braid.

    The correct choice is marked with a green star; its position is shuffled
    among the distractors so the mark, not the ordering, reveals it.
    """

    text_props = {"fontfamily": "monospace", "fontsize": 9}
    rows = []
    for choice_index, (is_correct, choice) in enumerate(choices):
        children = [TextArea(f"({_greek_label(choice_index)}) ", textprops={**text_props, "color": _INK})]
        for position_index, position in enumerate(query):
            separator = "" if position_index == 0 else ", "
            children.append(
                TextArea(f"{separator}{labels[position]}=", textprops={**text_props, "color": _INK})
            )
            value = choice[position]
            children.append(
                TextArea(
                    str(value),
                    textprops={**text_props, "color": colors[value], "fontweight": "bold"},
                )
            )
        # Every row reserves space for the same larger glyph, visible only on
        # the correct row, so the bigger star doesn't inflate just its row's
        # height and throw off the panel's vertical rhythm.
        children.append(
            TextArea(
                " ★",
                textprops={
                    **text_props,
                    "color": _CORRECT_MARK_COLOR,
                    "fontsize": 12,
                    "alpha": 1.0 if is_correct else 0.0,
                },
            )
        )
        rows.append(HPacker(children=children, align="baseline", pad=0, sep=0))
    stack = VPacker(children=rows, align="left", pad=0, sep=2)
    box = AnnotationBbox(
        stack,
        (anchor_x, 0.5),
        xycoords=("data", "axes fraction"),
        box_alignment=(0, 0.5),
        frameon=False,
        annotation_clip=False,
    )
    axis.add_artist(box)


def render_braid(
    record: dict[str, Any],
    *,
    output: Path,
    title: str | None,
    num_distractors: int = 4,
    distractor_seed: int = 0,
) -> None:
    """Draw live values flowing through registers across extra assignments."""

    state, operations = initial_state(record)
    labels = variable_labels(int(record["num_variables"]), record.get("temporary_variable"))
    temporary_row = record.get("temporary_variable")
    observed_values = sorted(
        set(state)
        | {int(operation["value"]) for operation in operations if operation["op"] == "constant"}
    )
    colors = _value_palette(observed_values)

    sns.set_theme(style="white", context="paper")
    # Pin DejaVu Sans everywhere; register names use DejaVu Sans Mono below.
    plt.rcParams["font.family"] = "sans-serif"
    plt.rcParams["font.sans-serif"] = ["DejaVu Sans"]
    plt.rcParams["font.monospace"] = ["DejaVu Sans Mono"]
    # Keep text as editable glyphs in vector output (.pdf / .svg).
    plt.rcParams["svg.fonttype"] = "none"
    plt.rcParams["pdf.fonttype"] = 42
    plt.rcParams["ps.fonttype"] = 42
    max_step = len(operations)
    width = min(30.0, max(6.5, 0.3 * (max_step + 1) + 1.6))
    height = max(1.1, 0.17 * len(labels) + 0.6)
    figure, axis = plt.subplots(figsize=(width, height))
    figure.patch.set_facecolor(_BACKGROUND)
    axis.set_facecolor(_BACKGROUND)

    # Faint full-width track behind every register; the scratch register is
    # dashed so it reads as auxiliary rather than a task variable.
    for row in range(len(labels)):
        axis.plot(
            [-0.15, max_step + 0.15],
            [row, row],
            color=_TRACK_COLOR,
            linewidth=1.4,
            linestyle=(0, (1, 2)) if row == temporary_row else "-",
            zorder=0.5,
            solid_capstyle="round",
        )

    # Simulate once, collecting whole-run horizontal strands (so casing does not
    # chop them into dashes), smooth copy crossings, and constant markers.
    initial = state.copy()
    run_start = [0] * len(state)
    horizontal_runs: list[tuple[int, int, int, int]] = []
    crossings: list[tuple[int, int, int, int, int]] = []
    constants: list[tuple[int, int, int]] = []
    for step, operation in enumerate(operations, start=1):
        target = int(operation["target"])
        horizontal_runs.append((target, run_start[target], step - 1, state[target]))
        if operation["op"] == "variable":
            source = int(operation["source"])
            new_value = state[source]
            crossings.append((step - 1, step, source, target, new_value))
        elif operation["op"] == "constant":
            new_value = int(operation["value"])
            constants.append((step, target, new_value))
        else:
            raise ValueError(f"unknown operation type: {operation['op']!r}")
        state[target] = new_value
        run_start[target] = step
    for row in range(len(state)):
        horizontal_runs.append((row, run_start[row], max_step, state[row]))

    if state != [int(value) for value in record["final_state"]]:
        raise ValueError("evaluated braid state does not match the record's final state")

    # Carried values (drawn first, so copy crossings weave over them).
    for row, x_start, x_end, value in horizontal_runs:
        if x_end > x_start:
            _draw_strand(axis, [x_start, x_end], [row, row], colors[value], zorder=2)
    for x0, x1, source, target, value in crossings:
        crossing_x, crossing_y = _smooth_crossing(x0, x1, source, target)
        _draw_strand(axis, crossing_x, crossing_y, colors[value], zorder=3)
    # Squares mark every value introduced by a constant assignment: the initial
    # register values and each mid-trace constant. Copies carry no marker.
    for step, target, value in [*((0, row, value) for row, value in enumerate(initial)), *constants]:
        axis.scatter(
            step, target, s=54, marker="s", color=colors[value],
            edgecolor=_BACKGROUND, linewidth=1.1, zorder=5,
        )

    # Read off the final state at the right edge, colored to match each strand.
    final_label_x = max_step + 0.35
    for row, value in enumerate(state):
        axis.text(
            final_label_x, row, str(value), va="center", ha="left",
            color=colors[value], fontweight="bold", fontsize=9, zorder=6,
        )

    # Enumerate the multiple-choice answers presented to the model, with each
    # value colored to match its strand so the correct choice is traceable by
    # eye even though it is shuffled in among the distractors.
    if num_distractors > 0:
        choices = _answer_choices(record, num_distractors=num_distractors, seed=distractor_seed)
        query = [int(value) for value in record["query"]]
        _draw_choices_panel(
            axis,
            anchor_x=final_label_x + 0.9,
            choices=choices,
            query=query,
            labels=labels,
            colors=colors,
        )

    axis.set_xticks(_time_ticks(max_step))
    axis.set_yticks(range(len(labels)))
    axis.set_yticklabels(labels, fontfamily="monospace")
    for tick_label, row in zip(axis.get_yticklabels(), range(len(labels)), strict=True):
        if row == temporary_row:
            tick_label.set_style("italic")
            tick_label.set_color("#8a8a92")
    axis.set_xlim(-0.6, max_step + 1.1)
    axis.set_ylim(len(labels) - 0.4, -0.6)
    axis.set_xlabel("assignment step", color=_INK)
    axis.tick_params(axis="both", length=0, colors=_INK)
    for spine in axis.spines.values():
        spine.set_visible(False)
    if title:
        axis.set_title(title, color=_INK, pad=12)

    output.parent.mkdir(parents=True, exist_ok=True)
    figure.savefig(output, dpi=300, bbox_inches="tight", facecolor=_BACKGROUND)
    plt.close(figure)


def main(argv: Sequence[str] | None = None) -> None:
    args = parse_args(argv)
    record = select_record(
        args.input,
        instance_id=args.instance_id,
        index=args.index,
        shortest=args.shortest,
    )
    render_braid(
        record,
        output=args.output,
        title=args.title,
        num_distractors=args.num_distractors,
        distractor_seed=args.distractor_seed,
    )
    print(
        json.dumps(
            {
                "output": str(args.output),
                "instance_id": record["instance_id"],
                "num_variables": record["num_variables"],
                "num_extra_assignments": record["num_extra_assignments"],
            },
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
